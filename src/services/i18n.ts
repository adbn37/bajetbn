function translateExact(value: string, language: Language): string {
  if (language !== 'ms') return value;
  const match = value.match(/^(\s*)(.*?)(\s*)$/s);
  if (!match) return value;
  const translated = malayPhrases[match[2]];
  return translated ? `${match[1]}${translated}${match[3]}` : value;
}

export function translatePhrase(language: Language, value: string): string {
  return translateExact(value, language);
}

const originalText = new WeakMap<Text, string>();
const translatedAttributes = ['placeholder', 'title', 'aria-label'] as const;

function localizeTextNode(node: Text, language: Language) {
  const parent = node.parentElement;
  if (!parent || parent.closest('script,style,code,pre,textarea,[data-no-auto-translate]')) return;
  if (!originalText.has(node)) originalText.set(node, node.nodeValue || '');
  const original = originalText.get(node) || '';
  const next = translateExact(original, language);
  if (node.nodeValue !== next) node.nodeValue = next;
}

function localizeElement(element: Element, language: Language) {
  translatedAttributes.forEach((attribute) => {
    const current = element.getAttribute(attribute);
    if (current === null) return;
    const originalAttribute = `data-bajetbn-original-${attribute}`;
    if (!element.hasAttribute(originalAttribute)) element.setAttribute(originalAttribute, current);
    const original = element.getAttribute(originalAttribute) || current;
    const next = translateExact(original, language);
    if (current !== next) element.setAttribute(attribute, next);
  });

  element.childNodes.forEach((child) => {
    if (child.nodeType === Node.TEXT_NODE) localizeTextNode(child as Text, language);
    else if (child.nodeType === Node.ELEMENT_NODE) localizeElement(child as Element, language);
  });
}

export function localizeDocument(language: Language, root: ParentNode = document) {
  const element = root instanceof Document ? root.documentElement : root instanceof Element ? root : null;
  if (element) localizeElement(element, language);
}
