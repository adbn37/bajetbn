import { createHash } from 'node:crypto';
import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIST_DIR = fileURLToPath(new URL('../dist/', import.meta.url));
const CACHEABLE_EXTENSIONS = new Set([
  '.html', '.js', '.css', '.png', '.svg', '.webmanifest', '.ico',
  '.woff', '.woff2', '.json',
]);

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const fullPath = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(fullPath));
    else files.push(fullPath);
  }
  return files;
}

function toUrl(filePath) {
  return `/${relative(DIST_DIR, filePath).split(sep).join('/')}`;
}

const allFiles = await walk(DIST_DIR);
const cacheableUrls = allFiles
  .filter((file) => !file.endsWith(`${sep}sw.js`))
  .filter((file) => !file.endsWith(`${sep}precache-manifest.json`))
  .filter((file) => !file.endsWith('.map'))
  .filter((file) => CACHEABLE_EXTENSIONS.has(extname(file).toLowerCase()))
  .map(toUrl)
  .sort();

const indexHtml = await readFile(join(DIST_DIR, 'index.html'), 'utf8');
const builtAssetUrls = Array.from(indexHtml.matchAll(/(?:src|href)=["'](\/assets\/[^"']+)["']/g))
  .map((match) => match[1]);

const criticalUrls = Array.from(new Set([
  '/index.html',
  ...builtAssetUrls,
]));

for (const url of criticalUrls) {
  if (url === '/index.html') continue;
  const filePath = join(DIST_DIR, url.slice(1));
  try {
    const info = await stat(filePath);
    if (!info.isFile()) throw new Error('not a file');
  } catch {
    throw new Error(`Critical PWA asset is missing from dist: ${url}`);
  }
}

const optionalUrls = cacheableUrls.filter((url) => !criticalUrls.includes(url));
const allPrecacheUrls = Array.from(new Set([...criticalUrls, ...optionalUrls]));

const hash = createHash('sha256');
for (const url of allPrecacheUrls) {
  hash.update(url);
  const filePath = join(DIST_DIR, url.slice(1));
  try {
    hash.update(await readFile(filePath));
  } catch {
    // Every URL is sourced from dist; this is defensive only.
  }
}
const buildHash = hash.digest('hex').slice(0, 12);
const cacheName = `bajetbn-shell-v0.1.2-${buildHash}`;

const report = {
  version: '0.1.2',
  cacheName,
  generatedAt: new Date().toISOString(),
  criticalUrls,
  optionalUrls,
};
await writeFile(
  join(DIST_DIR, 'precache-manifest.json'),
  `${JSON.stringify(report, null, 2)}\n`,
  'utf8',
);

const serviceWorker = `/* Generated by scripts/generate-service-worker.mjs. Do not edit dist/sw.js directly. */
const CACHE_NAME = ${JSON.stringify(cacheName)};
const APP_SHELL_URL = '/index.html';
const CRITICAL_URLS = ${JSON.stringify(criticalUrls, null, 2)};
const OPTIONAL_URLS = ${JSON.stringify(optionalUrls, null, 2)};
const PRECACHE_PATHS = new Set([...CRITICAL_URLS, ...OPTIONAL_URLS]);

async function fetchAndCache(cache, url, required) {
  try {
    const request = new Request(url, {
      cache: 'reload',
      credentials: 'same-origin',
    });
    const response = await fetch(request);
    if (!response.ok) throw new Error('HTTP ' + response.status);
    await cache.put(url, response.clone());
    return true;
  } catch (error) {
    console.error('[BajetBN PWA] Failed to precache', url, error);
    if (required) throw error;
    return false;
  }
}

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);

    // Cache the HTML, generated JavaScript, and generated CSS first. The new
    // worker is not allowed to activate unless the application shell is whole.
    for (const url of CRITICAL_URLS) {
      await fetchAndCache(cache, url, true);
    }

    // Icons and screenshots are useful but must never prevent an otherwise
    // healthy application shell from activating.
    await Promise.allSettled(
      OPTIONAL_URLS.map((url) => fetchAndCache(cache, url, false)),
    );

    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(
      keys
        .filter((key) => key.startsWith('bajetbn-shell-') && key !== CACHE_NAME)
        .map((key) => caches.delete(key)),
    );
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});

async function cachedByPath(request) {
  const pathname = new URL(request.url).pathname;
  const cache = await caches.open(CACHE_NAME);
  return cache.match(pathname, { ignoreSearch: true });
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        if (response.ok) return response;
      } catch {
        // Fall through to the cached SPA shell.
      }

      const cache = await caches.open(CACHE_NAME);
      const shell = await cache.match(APP_SHELL_URL, { ignoreSearch: true });
      if (shell) return shell;

      return new Response('BajetBN is offline and the application shell is not cached yet.', {
        status: 503,
        headers: { 'Content-Type': 'text/plain; charset=utf-8' },
      });
    })());
    return;
  }

  const pathname = url.pathname;
  if (PRECACHE_PATHS.has(pathname)) {
    event.respondWith((async () => {
      const cached = await cachedByPath(request);
      if (cached) return cached;

      const response = await fetch(request);
      if (response.ok) {
        const cache = await caches.open(CACHE_NAME);
        await cache.put(pathname, response.clone());
      }
      return response;
    })());
    return;
  }

  // Do not intercept unrelated same-origin requests injected by browser
  // extensions or DevTools. This avoids noisy rejected fetch promises offline.
});
`;

await writeFile(join(DIST_DIR, 'sw.js'), serviceWorker, 'utf8');
console.log(
  `Generated dist/sw.js with ${criticalUrls.length} critical and ${optionalUrls.length} optional files (${cacheName}).`,
);
